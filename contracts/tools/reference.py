"""Reference implementation of the shared RAG algorithms (docs/09-RAG.md).

This file is normative: the Go and Python servers must produce identical output
for the fixtures generated by `python3 contracts/tools/reference.py generate`.
Standard library only.
"""

from __future__ import annotations

import hashlib
import json
import math
import re
import struct
import sys
from pathlib import Path

MAX_CHUNK = 1200
EMBED_DIM = 768
WS = " \t\n\v\f\r"  # ASCII whitespace only
_HEADING = re.compile(r"^#{1,6} ")
_WS_RUN = re.compile(r"[ \t\n\v\f\r]+")
_TOKEN = re.compile(r"[A-Za-z0-9]+")


def normalize(text: str) -> str:
    if text.startswith("﻿"):
        text = text[1:]
    return text.replace("\r\n", "\n").replace("\r", "\n")


def content_hash(text: str) -> str:
    return hashlib.sha256(normalize(text).encode("utf-8")).hexdigest()


def _sections(text: str) -> list[tuple[str, list[str]]]:
    sections: list[tuple[str, list[str]]] = []
    heading, lines, in_fence = "", [], False
    for line in text.split("\n"):
        if line.startswith("```"):
            in_fence = not in_fence
            lines.append(line)
            continue
        if not in_fence and _HEADING.match(line):
            sections.append((heading, lines))
            heading = line.lstrip("#").strip(WS)
            lines = []
            continue
        lines.append(line)
    sections.append((heading, lines))
    return sections


def _paragraphs(lines: list[str]) -> list[str]:
    paras: list[str] = []
    cur: list[str] = []
    in_fence = False
    for line in lines:
        if line.startswith("```"):
            in_fence = not in_fence
        if not in_fence and line.strip(WS) == "" and not line.startswith("```"):
            if cur:
                paras.append("\n".join(cur))
                cur = []
            continue
        cur.append(line)
    if cur:
        paras.append("\n".join(cur))
    out = []
    for p in paras:
        p = p.strip(WS)
        if p:
            out.append(p)
    return out


def _split_long(p: str) -> list[str]:
    words: list[str] = []
    for w in _WS_RUN.split(p):
        if not w:
            continue
        while len(w) > MAX_CHUNK:
            words.append(w[:MAX_CHUNK])
            w = w[MAX_CHUNK:]
        if w:
            words.append(w)
    pieces: list[str] = []
    cur = ""
    for w in words:
        if cur == "":
            cur = w
        elif len(cur) + 1 + len(w) <= MAX_CHUNK:
            cur = cur + " " + w
        else:
            pieces.append(cur)
            cur = w
    if cur:
        pieces.append(cur)
    return pieces


def chunk(text: str) -> list[dict]:
    text = normalize(text)
    chunks: list[dict] = []
    for heading, lines in _sections(text):
        pieces: list[str] = []
        for p in _paragraphs(lines):
            if len(p) > MAX_CHUNK:
                pieces.extend(_split_long(p))
            else:
                pieces.append(p)
        cur = None
        for p in pieces:
            if cur is None:
                cur = p
            elif len(cur) + 2 + len(p) <= MAX_CHUNK:
                cur = cur + "\n\n" + p
            else:
                chunks.append({"heading": heading, "content": cur})
                cur = p
        if cur is not None:
            chunks.append({"heading": heading, "content": cur})
    return [{"chunk_index": i, **c} for i, c in enumerate(chunks)]


def embed_input(heading: str, content: str) -> str:
    return f"{heading}\n\n{content}" if heading else content


def fnv1a32(data: bytes) -> int:
    h = 2166136261
    for b in data:
        h ^= b
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def mock_embed(text: str) -> list[float]:
    v = [0.0] * EMBED_DIM
    for tok in _TOKEN.findall(text):
        h = fnv1a32(tok.lower().encode("ascii"))
        v[h % EMBED_DIM] += 1.0 if (h >> 31) == 0 else -1.0
    norm = math.sqrt(sum(x * x for x in v))
    if norm == 0:
        return v
    # round to float32, as stored in pgvector
    return [struct.unpack("f", struct.pack("f", x / norm))[0] for x in v]


def title_of(text: str, filename: str) -> str:
    for line in normalize(text).split("\n"):
        if line.startswith("# "):
            return line[2:].strip(WS)
    return filename


def generate(root: Path) -> None:
    fx = root / "contracts" / "fixtures"
    cases = sorted((fx / "rag-chunking" / "cases").glob("*"))
    for case in cases:
        if case.suffix not in (".md", ".txt"):
            continue
        text = case.read_bytes().decode("utf-8")
        out = {
            "source": case.name,
            "title": title_of(text, case.name),
            "content_hash": content_hash(text),
            "chunks": chunk(text),
        }
        (fx / "rag-chunking" / "expected" / (case.name + ".json")).write_text(
            json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
    texts = json.loads((fx / "rag-embed" / "texts.json").read_text(encoding="utf-8"))
    vectors = [mock_embed(t) for t in texts]
    (fx / "rag-embed" / "expected-mock.json").write_text(
        json.dumps({"dim": EMBED_DIM, "tolerance": 1e-6, "vectors": vectors}) + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "generate":
        (Path(__file__).resolve().parents[2] / "contracts/fixtures/rag-chunking/expected").mkdir(exist_ok=True)
        generate(Path(__file__).resolve().parents[2])
        print("fixtures generated")
    else:
        print(json.dumps(chunk(sys.stdin.read()), ensure_ascii=False, indent=2))
