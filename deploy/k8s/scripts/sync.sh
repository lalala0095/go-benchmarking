#!/usr/bin/env bash
# Copies files Kustomize needs into deploy/k8s/base/generated/ (git-ignored).
# Kustomize refuses to read files outside its directory tree, so db/init/* and
# corpus/** are copied in, plus a generated kustomization that turns them into
# ConfigMaps:
#   db-init     <- db/init/* (flat)          mounted at /docker-entrypoint-initdb.d
#   rag-corpus  <- corpus/**/*.{md,txt}      mounted at /corpus in both servers
# ConfigMap keys can't contain "/", so corpus/docs/01-PRD.md is stored under
# key "docs__01-PRD.md" and a generated patch maps it back to docs/01-PRD.md
# (volume `items`), so the in-pod tree matches Compose exactly.
set -euo pipefail
# shellcheck source=deploy/k8s/scripts/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

GEN="$K8S_DIR/base/generated"
DB_INIT="$REPO_ROOT/db/init"
CORPUS="$REPO_ROOT/corpus"
# ConfigMaps max out at 1 MiB (etcd object limit). Keep headroom for metadata.
MAX_CORPUS_BYTES="${MAX_CORPUS_BYTES:-921600}"   # 900 KB

[[ -d "$DB_INIT" ]] || die "missing $DB_INIT"

rm -rf "$GEN"
mkdir -p "$GEN/db-init" "$GEN/corpus"

# --- db-init ---------------------------------------------------------------
db_files=()
while IFS= read -r -d '' f; do
  db_files+=("$(basename "$f")")
done < <(find "$DB_INIT" -mindepth 1 -maxdepth 1 -print0 | LC_ALL=C sort -z)
for f in "${db_files[@]}"; do
  [[ -f "$DB_INIT/$f" ]] || die "db/init/$f is not a regular file: a ConfigMap mount is flat, keep db/init without subdirectories"
  cp -p "$DB_INIT/$f" "$GEN/db-init/$f"
done
log "db-init: ${#db_files[@]} files"

# --- rag-corpus ------------------------------------------------------------
keys=() paths=() total=0 skipped=0
if [[ -d "$CORPUS" ]]; then
  while IFS= read -r -d '' f; do
    rel="${f#"$CORPUS"/}"
    case "$rel" in
      private/*) continue ;;                # never ship private docs into the cluster
      *.md|*.txt) ;;
      *) skipped=$((skipped + 1)); continue ;;
    esac
    key="${rel//\//__}"
    [[ "$key" =~ ^[-._a-zA-Z0-9]+$ && ${#key} -le 253 ]] \
      || die "corpus/$rel: only [-._a-zA-Z0-9/] are allowed in corpus paths (ConfigMap key rules). Rename it."
    [[ ! -e "$GEN/corpus/$key" ]] || die "corpus/$rel collides with another file as key '$key'"
    cp "$f" "$GEN/corpus/$key"
    total=$((total + $(wc -c <"$f")))
    keys+=("$key")
    paths+=("$rel")
  done < <(find "$CORPUS" -type f -print0 | LC_ALL=C sort -z)
fi
(( skipped == 0 )) || warn "skipped $skipped corpus file(s) that are not .md/.txt"
if (( total > MAX_CORPUS_BYTES )); then
  die "corpus is $total bytes (> $MAX_CORPUS_BYTES): too big for a ConfigMap. Trim corpus/ or use the HTTP ingest API (docs/09-RAG.md §1)."
fi
log "rag-corpus: ${#keys[@]} files, $total bytes (limit $MAX_CORPUS_BYTES)"

# --- generated/kustomization.yaml ------------------------------------------
{
  echo "# GENERATED by deploy/k8s/scripts/sync.sh — do not edit, re-run make k8s-sync."
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "configMapGenerator:"
  echo "  - name: db-init"
  echo "    files:"
  for f in "${db_files[@]}"; do echo "      - \"db-init/$f\""; done
  echo "  - name: rag-corpus"
  if (( ${#keys[@]} == 0 )); then
    echo "    literals: []"
  else
    echo "    files:"
    for k in "${keys[@]}"; do echo "      - \"corpus/$k\""; done
  fi
} >"$GEN/kustomization.yaml"

# --- generated/corpus-volume-patch.yaml ------------------------------------
# Strategic merge: volumes merge by name, configMap.name stays from the base.
items_yaml() {
  local i
  (( ${#keys[@]} > 0 )) || return 0   # empty corpus: nothing to map
  echo "            items:"
  for i in "${!keys[@]}"; do
    echo "              - key: \"${keys[$i]}\""
    echo "                path: \"${paths[$i]}\""
  done
}
{
  echo "# GENERATED by deploy/k8s/scripts/sync.sh — do not edit, re-run make k8s-sync."
  first=1
  for dep in go-server fastapi-server; do
    (( first )) || echo "---"
    first=0
    cat <<YAML
apiVersion: apps/v1
kind: Deployment
metadata:
  name: $dep
spec:
  template:
    spec:
      volumes:
        - name: corpus
          configMap:
            name: rag-corpus
YAML
    items_yaml
  done
} >"$GEN/corpus-volume-patch.yaml"

log "wrote ${GEN#"$REPO_ROOT"/}/ (git-ignored)"
