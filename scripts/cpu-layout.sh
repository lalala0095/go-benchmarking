#!/usr/bin/env bash
# Prints (and with --write, writes) a CPU-pinning layout for docker-compose.bench.yml.
# Works on PHYSICAL cores so SMT siblings (on the 4600G: CPU n and n+6) are never
# split between two owners, which would make them share execution units:
#   core 0           -> OS, sshd, k3s (left unassigned)
#   next 3 cores     -> postgres, go-server, fastapi-server (one full core each)
#   remaining cores  -> dashboard / load generator
# Usage: ./scripts/cpu-layout.sh [--write] [--from FILE]
#   --write      overwrite docker-compose.bench.yml (default: print only)
#   --from FILE  read `lscpu -e=CPU,CORE` output from FILE (testing / other hosts)
set -euo pipefail

if (( BASH_VERSINFO[0] < 4 )); then
  echo "error: needs bash >= 4 (associative arrays). On Linux /usr/bin/env bash is fine." >&2
  exit 1
fi

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$REPO_ROOT/docker-compose.bench.yml"
WRITE=0 FROM=""
while (( $# )); do
  case "$1" in
    --write) WRITE=1 ;;
    --from) FROM="${2:?--from needs a file}"; shift ;;
    -h|--help) sed -n '2,11p' "$0"; exit 0 ;;
    *) echo "unknown option: $1 (see --help)" >&2; exit 2 ;;
  esac
  shift
done

if [[ -n "$FROM" ]]; then
  lscpu_out="$(cat "$FROM")"
elif command -v lscpu >/dev/null 2>&1; then
  lscpu_out="$(lscpu -e=CPU,CORE)"
else
  echo "error: lscpu not found. CPU pinning (cpuset) is Linux-only; Docker Desktop on macOS runs containers in a VM, so pinning there is meaningless. Run this on the Ubuntu server." >&2
  exit 1
fi

# Group logical CPUs by physical core: cpus_of[core]="0,6". Skips the header
# and offline CPUs (lscpu prints "-" for their core).
declare -A cpus_of=()
while read -r cpu core _; do
  [[ "$cpu" =~ ^[0-9]+$ && "$core" =~ ^[0-9]+$ ]] || continue
  cpus_of[$core]="${cpus_of[$core]:+${cpus_of[$core]},}$cpu"
done <<<"$lscpu_out"

mapfile -t cores < <(printf '%s\n' "${!cpus_of[@]}" | sort -n)
ncores=${#cores[@]}
if (( ncores < 5 )); then
  echo "error: found $ncores physical cores; this layout needs at least 5 (OS + postgres + go + python + dashboard)." >&2
  echo "       on smaller machines skip pinning (make up) and lower SERVER_CPUS / DASH_CPUS in .env." >&2
  exit 1
fi

sort_cpus() { tr ',' '\n' | sort -n | paste -sd, -; }
os="$(sort_cpus <<<"${cpus_of[${cores[0]}]}")"
pg="$(sort_cpus <<<"${cpus_of[${cores[1]}]}")"
go="$(sort_cpus <<<"${cpus_of[${cores[2]}]}")"
py="$(sort_cpus <<<"${cpus_of[${cores[3]}]}")"
dash_list=""
for c in "${cores[@]:4}"; do dash_list+="${dash_list:+,}${cpus_of[$c]}"; done
dash="$(sort_cpus <<<"$dash_list")"

total_cpus=$(tr ',' '\n' <<<"$os,$pg,$go,$py,$dash" | wc -l | tr -d ' ')
threads_per_core=$(( total_cpus / ncores ))
model="$(lscpu 2>/dev/null | sed -n 's/^Model name:[[:space:]]*//p' | head -1 || true)"

cat >&2 <<INFO
detected $ncores physical cores, $total_cpus logical CPUs (${threads_per_core} per core)${model:+, $model}
  OS / sshd / k3s : $os
  postgres        : $pg
  go-server       : $go
  fastapi-server  : $py
  dashboard       : $dash
INFO

render() {
  cat <<YAML
# CPU pinning overlay for official numbers. Generated by scripts/cpu-layout.sh
# for ${model:-this host} ($ncores cores / $total_cpus threads). Usage: make up-bench
# core0 ($os): OS + sshd + k3s · postgres ($pg) · go ($go) · python ($py) · dashboard/loadgen ($dash)
services:
  postgres:       { cpuset: "$pg" }
  go-server:      { cpuset: "$go" }
  fastapi-server: { cpuset: "$py" }
  dashboard:      { cpuset: "$dash" }
YAML
}

if (( WRITE )); then
  render >"$OUT"
  echo "wrote $OUT" >&2
else
  render
  echo "(print only; re-run with --write to update docker-compose.bench.yml)" >&2
fi
